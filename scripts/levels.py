#!/usr/bin/env python3
"""Measure every sound and write js/levels.js: a gain per file so the ambient beds sit at one level
and the one-shots at another, and the loop period of every seamless bed (LOOPS, in samples at
44.1 kHz; see scripts/gen_sfx.py). Run again after adding or regenerating sounds (needs ffmpeg)."""
import json, pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET_AMB = -28.0     # ambient beds: mean dB
TARGET_PEAK = -5.0     # one-shots: peak dB (a two-second ladle hit is mostly silence, so its mean says little)
QUIET_ON_PURPOSE = {"amb_cells"}        # the cells are meant to be near silence
BEDS = {"pulse", "ru_mess_murmur"}      # loops whose names do not say so
TRIM = {"amb_hut": -3.0}                # dB under the matched level: the sleeping hut should be gentle

def measure(path):
    out = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "volumedetect", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    return (float(re.search(r"mean_volume: (-?[0-9.]+) dB", out).group(1)),
            float(re.search(r"max_volume: (-?[0-9.]+) dB", out).group(1)))

def period(path):
    tag = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format_tags=comment", "-of", "csv=p=0", str(path)],
                         capture_output=True, text=True).stdout.split()
    return int(tag[1]) if len(tag) == 2 and tag[0] == "seamless" and tag[1].isdigit() else None

gains, loops = {}, {}
for f in sorted((ROOT / "assets/sfx").glob("*.mp3")):
    name = f.stem
    mean, peak = measure(f)
    p = period(f)
    if p:
        loops[name] = p
    bed = name.startswith(("amb_", "bed_")) or name in BEDS or p is not None
    if name in QUIET_ON_PURPOSE:
        g = 10 ** (12 / 20)       # lift it a little, but keep it quiet
    elif bed:
        g = 10 ** ((TARGET_AMB - mean) / 20)
    else:
        g = 10 ** ((TARGET_PEAK - peak) / 20)
    g *= 10 ** (TRIM.get(name, 0) / 20)
    gains[name] = round(min(g, 6.0), 3)
    print(f"  {name:16s} {'bed' if bed else 'hit'}  mean {mean:6.1f} dB  peak {peak:6.1f} dB  gain {gains[name]}{'  loop ' + str(p) if p else ''}")
(ROOT / "js/levels.js").write_text(
    "'use strict';\n// Generated by scripts/levels.py: a gain per sound so they sit at matched loudness,\n"
    "// and for each seamless loop its period in samples at 44.1 kHz (js/audio.js loops from 0.15 s to 0.15 s + period).\n"
    f"const LEVELS = {json.dumps(gains, indent=2)};\n"
    f"const LOOPS = {json.dumps(loops, indent=2)};\n")
print("wrote js/levels.js")
